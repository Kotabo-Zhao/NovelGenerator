def match_playbook(genre: str) -> str:
    """按题材匹配流派（返回流派名或 '通用'）"""
    if not genre:
        return "通用"
    for keywords, name in GENRE_RULES:
        if any(k in genre for k in keywords):
            return name
    return "通用"


def build_playbook_context(genre: str) -> str:
    """构建流派法则注入文本（通用铁律 + 流派专属）"""
    name = match_playbook(genre)
    parts = [COMMON_RULES]
    if name != "通用":
        parts.append(PLAYBOOKS[name])
    return "\n\n".join(parts)


def get_playbook_name(genre: str) -> str:
    """返回匹配的流派名（用于元数据展示）"""
    return match_playbook(genre)
