    def fetch_trending_novels(self, max_count: int = 20) -> list:
        """从多个平台抓取热门小说榜单
        
        Returns:
            [{"title": str, "author": str, "genre": str, "tags": [str], 
              "popularity": int, "intro": str, "source": str}, ...]
        """
        novels = []
        
        # 尝试抓取起点中文网热门
        try:
            req = Request("https://www.qidian.com/rank/hotsales/", 
                         headers={"User-Agent": "Mozilla/5.0"})
            with urlopen(req, timeout=15) as resp:
                html = resp.read().decode("utf-8", errors="ignore")
                # 提取书名和作者
                titles = re.findall(r'data-bid="\d+".*?<h2>(.*?)</h2>', html, re.DOTALL)
                authors = re.findall(r'<a class="name".*?>(.*?)</a>', html)
                genres = re.findall(r'<a href="/mm/category/.*?".*?>(.*?)</a>', html)
                
                for i in range(min(len(titles), max_count)):
                    title = re.sub(r'<[^>]+>', '', titles[i]).strip()
                    novels.append({
                        "title": title,
                        "author": authors[i].strip() if i < len(authors) else "未知",
                        "genre": genres[i].strip() if i < len(genres) else "玄幻",
                        "tags": [],
                        "popularity": 1000 - i * 30,
                        "intro": "",
                        "source": "qidian",
                    })
                log.info(f"Scraped {len(novels)} novels from Qidian")
        except Exception as e:
            log.warning(f"Qidian scrape failed: {e}, using built-in data")
        
        # 兜底：内置热门小说数据（离线可用）
        if not novels:
            novels = self._get_builtin_hot_novels(max_count)
        
        return novels[:max_count]
    
