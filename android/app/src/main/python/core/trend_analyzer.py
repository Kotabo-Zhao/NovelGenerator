def quick_bizarre(count: int = 3, genre: str = None, mode: str = "topical",
                  news_items: list = None) -> list:
    """快速生成逆天小说设定
    
    Args:
        count: 数量
        genre: 类型过滤
        mode: "topical"=时事离谱(默认) "twist"=剧情反转 "mixed"=混合
        news_items: 预抓取的热点新闻。为None时自动抓取。
    """
    gen = BizarreNovelGenerator()
    novels = []
    
    for i in range(count):
        seed = i * 42 + int(time.time()) % 1000
        
        if mode == "topical":
            # 从热点新闻动态生成
            if news_items is None:
                news_items = gen.fetch_hot_news(10)
            premises = gen.generate_topical_from_news(news_items, seed=seed, count=1)
            if premises:
                premise = premises[0]
            else:
                # 极端fallback: 用静态库
                premise = gen.generate_topical_premise(seed=seed)
        elif mode == "twist":
            premise = gen.generate_bizarre_premise(None, seed=seed, genre=genre)
        else:  # mixed
            if i % 2 == 0:
                if news_items is None:
                    news_items = gen.fetch_hot_news(10)
                premises = gen.generate_topical_from_news(news_items, seed=seed, count=1)
                premise = premises[0] if premises else gen.generate_topical_premise(seed=seed)
            else:
                premise = gen.generate_bizarre_premise(None, seed=seed, genre=genre)
        
        novels.append({"premise": premise, "outline": gen._generate_fallback_outline(premise)})
    return novels
