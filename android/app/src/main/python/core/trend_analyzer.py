    async def full_pipeline(self, count: int = 5, style: str = "热血爽文",
                            theme: str = "", genre: str = "") -> dict:
        """全流程：分析趋势 → 模板基因 → 种子生成 → 大纲展开
        
        Returns:
            {"trends": {...}, "bizarre_novels": [{...}, ...]}
        """
        log.info("Step 1: Fetching trending novels...")
        novels = self.analyzer.fetch_trending_novels(20)
        
        log.info("Step 2: Analyzing patterns...")
        patterns = self.analyzer.extract_patterns(novels)
        
        if self.client:
            deep = await self.analyzer.deep_analyze(novels, theme)
            patterns["deep_analysis"] = deep
        
        log.info(f"Step 3: Generating {count} bizarre novels...")
        bizarre_novels = []
        used_ids = set()
        
        for i in range(count):
            seed = int(time.time() * 1000 + i * 777) % (2**31)
            
            # 避免重复模板
            if i < len(PLOT_TWISTS) and not self.client:
                available = [t for t in PLOT_TWISTS if t["id"] not in used_ids]
                if available:
                    random.seed(seed)
                    template = random.choice(available)
                    used_ids.add(template["id"])
                    premise = self.generate_bizarre_premise(patterns, seed=seed, genre=template["genre"])
                else:
                    premise = self.generate_bizarre_premise(patterns, seed=seed, genre=genre)
            elif self.client and i < 3:
                # LLM 融合模式：前3个用 LLM 增强
                premise = self._generate_bizarre_premise_llm(patterns, seed, genre)
            else:
                premise = self.generate_bizarre_premise(patterns, seed=seed, genre=genre)
            
            if self.client and i < 3:
                outline = await self.generate_full_novel(premise, style)
            else:
                outline = self._generate_fallback_outline(premise)
            
            bizarre_novels.append({
                "premise": premise,
                "outline": outline,
            })
        
        return {
            "trends": patterns,
            "hot_novels": [{"title": n["title"], "author": n["author"], "genre": n["genre"],
                          "tags": n.get("tags",[])} for n in novels[:10]],
            "bizarre_novels": bizarre_novels,
        }


